function dialogue(opening, detail, category) {
  return {
    start: {
      message: opening,
      options: [
        {
          id: "detail",
          label: "Pode detalhar o que você precisa?",
          next: "detail",
        },
        {
          id: "context",
          label: "Onde você está tentando fazer isso?",
          next: "context",
        },
      ],
    },
    detail: {
      message: detail,
      options: [
        {
          id: "context",
          label: "Em qual aplicativo ou local?",
          next: "context",
        },
      ],
    },
    context: {
      message:
        "Estou neste computador, na parte de " +
        category +
        ". Pode acessar para conferir. " +
        detail,
      options: [
        {
          id: "detail",
          label: "Pode repetir os dados do pedido?",
          next: "detail",
        },
      ],
    },
  };
}
